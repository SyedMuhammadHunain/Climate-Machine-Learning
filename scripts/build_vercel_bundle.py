"""Build the Vercel deploy bundle: the FastAPI app plus the HTML pages, with a lean requirements.txt.

Run:  python scripts/build_vercel_bundle.py [--out vercel_bundle]
Why a separate folder: the repo's requirements.txt is the whole development environment (Jupyter, plotting,
about 120 packages). A serverless function must carry only what the API needs at run time.
Writes (nothing is uploaded here): app/, src/climate_machine_learning/ (3 modules), models/, data/reference/,
frontend/, requirements.txt (exact pins, transitive closure of the runtime packages), .python-version.
"""
import shutil
import sys
from importlib.metadata import requires
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

from bundle_util import UnsafeOutputDir, prepare_out  # noqa: F401  (UnsafeOutputDir is part of this module's API)

ROOT = Path(__file__).resolve().parent.parent
MARKER = ".built-by-build_vercel_bundle"
OWNED = ("app", "src", "models", "data", "frontend", "requirements.txt", ".python-version")
RUNTIME_PACKAGES = ("fastapi", "pydantic", "scikit-learn", "pandas", "numpy", "joblib")
PYTHON_VERSION = "3.12"
SRC_MODULES = ("__init__.py", "features.py", "inference.py")   # training.py and presentation.py are not needed by the API
MODEL_FILES = ("crop_yield_pipeline.joblib", "reference.json", "metrics.json")
FRONTEND = Path("frontend") / "climate-resilient-frontend"
# markers are judged for the function's runtime (Linux, Python 3.12), not for the machine that builds the bundle
TARGET_ENV = {"extra": "", "python_version": PYTHON_VERSION, "python_full_version": PYTHON_VERSION + ".0",
              "sys_platform": "linux", "platform_system": "Linux", "os_name": "posix"}


def root_pins() -> dict:
    pins = {}
    for line in (ROOT / "requirements.txt").read_text().splitlines():
        if "==" in line and not line.startswith("#"):
            name, version = line.strip().split("==", 1)
            pins[canonicalize_name(name)] = (name, version)
    return pins


def lean_requirements() -> list:
    """Exact pins for the runtime packages and everything they need, taken from the tested requirements.txt."""
    pins, seen, todo = root_pins(), set(), list(RUNTIME_PACKAGES)
    while todo:
        name = canonicalize_name(todo.pop())
        if name in seen:
            continue
        seen.add(name)
        for text in requires(name) or []:
            req = Requirement(text)
            if req.marker is None or req.marker.evaluate(TARGET_ENV):
                todo.append(req.name)
    missing = sorted(n for n in seen if n not in pins)
    if missing:
        raise RuntimeError(f"not pinned in requirements.txt: {missing}")
    return sorted(f"{pins[n][0]}=={pins[n][1]}" for n in seen)


def build(out: Path) -> Path:
    out = prepare_out(out, OWNED, MARKER)
    ignore = shutil.ignore_patterns("__pycache__", "*.pyc")
    shutil.copytree(ROOT / "app", out / "app", ignore=ignore)

    (out / "src" / "climate_machine_learning").mkdir(parents=True)
    for name in SRC_MODULES:
        shutil.copy2(ROOT / "src" / "climate_machine_learning" / name, out / "src" / "climate_machine_learning" / name)

    (out / "models").mkdir()
    for name in MODEL_FILES:
        shutil.copy2(ROOT / "models" / name, out / "models" / name)

    (out / "data" / "reference").mkdir(parents=True)
    shutil.copy2(ROOT / "data" / "reference" / "fao_crop_water_needs.json", out / "data" / "reference")

    # pages are served by the app; package.json and the README are not part of the site
    shutil.copytree(ROOT / FRONTEND, out / FRONTEND, ignore=shutil.ignore_patterns("__pycache__", "package.json", "README.md", "node_modules"))

    header = "# generated by scripts/build_vercel_bundle.py from requirements.txt (exact pins); do not edit\n"
    (out / "requirements.txt").write_text(header + "\n".join(lean_requirements()) + "\n")
    (out / ".python-version").write_text(PYTHON_VERSION + "\n")
    return out


if __name__ == "__main__":
    target = Path(sys.argv[sys.argv.index("--out") + 1]) if "--out" in sys.argv else ROOT / "vercel_bundle"
    try:
        build(target)
    except UnsafeOutputDir as err:
        sys.exit(f"error: {err}")
    files = [p for p in sorted(target.rglob("*")) if p.is_file()]
    print(f"built {target}: {len(files)} files, {sum(p.stat().st_size for p in files)/1e6:.1f} MB, "
          f"{len((target / 'requirements.txt').read_text().splitlines()) - 1} pinned packages")
